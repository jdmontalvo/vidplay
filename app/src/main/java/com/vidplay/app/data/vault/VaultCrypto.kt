package com.vidplay.app.data.vault

import java.io.File
import java.io.InputStream
import java.io.OutputStream
import java.io.RandomAccessFile
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.nio.file.Files
import java.nio.file.StandardCopyOption
import java.security.MessageDigest
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Chunked AES-256-GCM container.
 *
 * Layout:
 *   56-byte header (magic, version, flags, chunk size, plain size, SHA-256)
 *   For every chunk: 12-byte random IV + ciphertext + 16-byte GCM tag.
 *
 * The IV is generated by the platform CSPRNG for every chunk. GCM authenticates
 * every chunk, and the header SHA-256 lets us verify the whole file on export.
 */
object VaultCrypto {
    const val HEADER_SIZE = 56
    const val CHUNK_SIZE = 1 shl 20 // 1 MiB
    const val IV_SIZE = 12
    const val TAG_SIZE = 16
    private val MAGIC = byteArrayOf(
        'V'.code.toByte(), 'P'.code.toByte(), 'V'.code.toByte(), 'P'.code.toByte(),
        'L'.code.toByte(), 'A'.code.toByte(), 'Y'.code.toByte(), '1'.code.toByte(),
    )
    private const val VERSION: Byte = 1
    private val random = SecureRandom()

    data class Header(
        val plainSize: Long,
        val sha256: ByteArray,
        val chunkSize: Int = CHUNK_SIZE,
    ) {
        val chunkCount: Long
            get() = if (plainSize == 0L) 0L else ((plainSize - 1) / chunkSize) + 1

        fun plainSizeOfChunk(index: Long): Int {
            val start = index * chunkSize
            return (plainSize - start).coerceAtMost(chunkSize.toLong()).toInt().coerceAtLeast(0)
        }
    }

    fun randomKey(): SecretKey {
        val bytes = ByteArray(32)
        random.nextBytes(bytes)
        return SecretKeySpec(bytes, "AES")
    }

    fun sha256Hex(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    fun sha256Hex(text: String): String = sha256Hex(text.toByteArray(Charsets.UTF_8))

    suspend fun encrypt(
        input: InputStream,
        target: File,
        key: SecretKey,
        expectedSize: Long = -1L,
        onProgress: suspend (Long) -> Unit = {},
    ): Header {
        val parent = target.parentFile ?: error("Sin carpeta destino")
        if (!parent.exists()) parent.mkdirs()
        val temp = File(parent, "${target.name}.part")
        temp.delete()
        val digest = MessageDigest.getInstance("SHA-256")
        val chunk = ByteArray(CHUNK_SIZE)
        var total = 0L
        try {
            RandomAccessFile(temp, "rw").use { raf ->
                raf.setLength(HEADER_SIZE.toLong())
                raf.seek(HEADER_SIZE.toLong())
                while (true) {
                    val read = readFully(input, chunk, 0, chunk.size)
                    if (read <= 0) break
                    digest.update(chunk, 0, read)
                    val iv = ByteArray(IV_SIZE)
                    random.nextBytes(iv)
                    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
                    cipher.init(Cipher.ENCRYPT_MODE, key, GCMParameterSpec(128, iv))
                    val encrypted = cipher.doFinal(chunk, 0, read)
                    raf.write(iv)
                    raf.write(encrypted)
                    total += read
                    onProgress(total)
                }
                val header = Header(plainSize = total, sha256 = digest.digest())
                raf.seek(0L)
                raf.write(headerBytes(header))
                raf.fd.sync()
            }
            moveAtomic(temp, target)
            return readHeader(target)
        } catch (t: Throwable) {
            temp.delete()
            throw t
        } finally {
            // expectedSize is only a hint; the real size is in the header.
            if (expectedSize > 0 && total == 0L) {
                // Nothing to do; keeps the parameter meaningful for callers.
            }
        }
    }

    suspend fun decrypt(
        source: File,
        output: OutputStream,
        key: SecretKey,
        verifyHash: Boolean = true,
        onProgress: suspend (Long, Long) -> Unit = { _, _ -> },
    ): Header {
        val header = readHeader(source)
        val digest = MessageDigest.getInstance("SHA-256")
        var written = 0L
        RandomAccessFile(source, "r").use { raf ->
            for (index in 0 until header.chunkCount) {
                val plain = decryptChunk(raf, header, index, key)
                digest.update(plain)
                output.write(plain)
                written += plain.size
                onProgress(written, header.plainSize)
            }
        }
        output.flush()
        if (verifyHash && !MessageDigest.isEqual(digest.digest(), header.sha256)) {
            throw SecurityException("El hash del vídeo restaurado no coincide")
        }
        return header
    }

    fun readHeader(file: File): Header {
        if (!file.exists() || file.length() < HEADER_SIZE) {
            throw IllegalArgumentException("Archivo del baúl incompleto")
        }
        val buffer = ByteArray(HEADER_SIZE)
        RandomAccessFile(file, "r").use { raf ->
            raf.readFully(buffer)
        }
        val bb = ByteBuffer.wrap(buffer).order(ByteOrder.BIG_ENDIAN)
        val magic = ByteArray(8).also { bb.get(it) }
        if (!magic.contentEquals(MAGIC)) throw IllegalArgumentException("Formato de baúl no válido")
        val version = bb.get()
        if (version != VERSION) throw IllegalArgumentException("Versión de baúl no soportada")
        bb.get() // flags
        bb.short // reserved
        val chunkSize = bb.int
        if (chunkSize <= 0 || chunkSize > 16 * 1024 * 1024) {
            throw IllegalArgumentException("Tamaño de bloque no válido")
        }
        val plainSize = bb.long
        val sha = ByteArray(32).also { bb.get(it) }
        if (plainSize < 0) throw IllegalArgumentException("Tamaño de archivo no válido")
        val expected = expectedEncryptedSize(plainSize, chunkSize)
        if (file.length() < expected) throw IllegalArgumentException("Archivo del baúl truncado")
        return Header(plainSize = plainSize, sha256 = sha, chunkSize = chunkSize)
    }

    fun decryptChunk(
        raf: RandomAccessFile,
        header: Header,
        index: Long,
        key: SecretKey,
    ): ByteArray {
        if (index < 0 || index >= header.chunkCount) return ByteArray(0)
        val plainLength = header.plainSizeOfChunk(index)
        val offset = HEADER_SIZE + index * (header.chunkSize + IV_SIZE + TAG_SIZE)
        raf.seek(offset)
        val iv = ByteArray(IV_SIZE)
        raf.readFully(iv)
        val encrypted = ByteArray(plainLength + TAG_SIZE)
        raf.readFully(encrypted)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(128, iv))
        return cipher.doFinal(encrypted)
    }

    fun encryptBytes(plain: ByteArray, key: SecretKey): ByteArray {
        val iv = ByteArray(IV_SIZE)
        random.nextBytes(iv)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, key, GCMParameterSpec(128, iv))
        return iv + cipher.doFinal(plain)
    }

    fun decryptBytes(encrypted: ByteArray, key: SecretKey): ByteArray {
        if (encrypted.size <= IV_SIZE) throw IllegalArgumentException("Blob cifrado no válido")
        val iv = encrypted.copyOfRange(0, IV_SIZE)
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(128, iv))
        return cipher.doFinal(encrypted, IV_SIZE, encrypted.size - IV_SIZE)
    }

    fun expectedEncryptedSize(plainSize: Long, chunkSize: Int = CHUNK_SIZE): Long {
        if (plainSize == 0L) return HEADER_SIZE.toLong()
        val fullChunks = plainSize / chunkSize
        val remainder = plainSize % chunkSize
        val overhead = (IV_SIZE + TAG_SIZE).toLong()
        return HEADER_SIZE.toLong() + plainSize + fullChunks * overhead +
            if (remainder > 0) overhead else 0L
    }

    private fun headerBytes(header: Header): ByteArray {
        val bb = ByteBuffer.allocate(HEADER_SIZE).order(ByteOrder.BIG_ENDIAN)
        bb.put(MAGIC)
        bb.put(VERSION)
        bb.put(0) // flags
        bb.putShort(0)
        bb.putInt(header.chunkSize)
        bb.putLong(header.plainSize)
        bb.put(header.sha256)
        return bb.array()
    }

    private fun readFully(input: InputStream, buffer: ByteArray, offset: Int, length: Int): Int {
        var total = 0
        while (total < length) {
            val read = input.read(buffer, offset + total, length - total)
            if (read < 0) break
            if (read == 0) continue
            total += read
        }
        return total
    }

    private fun moveAtomic(source: File, target: File) {
        try {
            Files.move(
                source.toPath(),
                target.toPath(),
                StandardCopyOption.REPLACE_EXISTING,
                StandardCopyOption.ATOMIC_MOVE,
            )
        } catch (_: Exception) {
            Files.move(source.toPath(), target.toPath(), StandardCopyOption.REPLACE_EXISTING)
        }
    }
}
